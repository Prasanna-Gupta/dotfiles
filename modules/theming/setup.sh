#!/usr/bin/env bash
# Theming engine setup: matugen config, systemd watcher, SDDM ownership, sudoers.
set -euo pipefail
DOTFILES="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# shellcheck source=../../lib/common.sh
source "$DOTFILES/lib/common.sh"

T="$DOTFILES/modules/theming"
STATE="${XDG_STATE_HOME:-$HOME/.local/state}/prasanna"
SDDM_THEME=/usr/share/sddm/themes/silent
# Files matugen writes must be yours (v1 created some via sudo)
for f in "$HOME/.config/kitty/theme.conf" "$STATE/colors.json"; do
    [[ -e "$f" && ! -O "$f" ]] && run sudo chown "$USER:" "$f"
done
run mkdir -p "$STATE/logs" "$HOME/.config/matugen" "$HOME/.local/bin" "$HOME/.config/kitty"

step "Theming engine"

# v1 left hooks + orchestrator copies in ~/.config/prasanna — retire them
if [[ -d "$HOME/.config/prasanna" ]]; then
    warn "Retiring v1 engine files in ~/.config/prasanna → $STATE/v1-backup"
    run mkdir -p "$STATE/v1-backup"
    run cp -a "$HOME/.config/prasanna/." "$STATE/v1-backup/"
    run rm -rf "$HOME/.config/prasanna"
fi
run rm -f "$HOME/.config/matugen/templates/sddm.conf.tmpl" "$HOME/.config/matugen/templates/kitty-theme.conf"

symlink "$T/update.sh" "$HOME/.local/bin/prasanna-theme"

# SDDM (SilentSDDM) — optional. Dir is user-owned so matugen can write it without sudo.
sddm_enabled=false
if [[ -d "$SDDM_THEME" ]]; then
    sddm_enabled=true
    run sudo mkdir -p /etc/sddm-prasanna
    run sudo chown -R "$USER:" /etc/sddm-prasanna
    [[ -f /etc/sddm-prasanna/prasanna.conf ]] || run cp "$T/templates/sddm.conf.tmpl" /etc/sddm-prasanna/prasanna.conf
    if [[ ! -L "$SDDM_THEME/configs/prasanna.conf" ]]; then
        run sudo ln -sf /etc/sddm-prasanna/prasanna.conf "$SDDM_THEME/configs/prasanna.conf"
    fi
    run sudo setfacl -m "u:$USER:rwx" "$SDDM_THEME/backgrounds"
    log "SDDM (SilentSDDM) wired up"
else
    warn "SilentSDDM not found at $SDDM_THEME — login-screen sync disabled (everything else works)"
fi

# matugen config: generated (contains absolute paths), never tracked
cfg="$HOME/.config/matugen/config.toml"
if [[ "$DRY_RUN" != true ]]; then
    {
        echo "# Generated by Prasanna OS (modules/theming/setup.sh) — edit the generator, not this file"
        echo "[config]"
        echo
        echo "[templates.kitty]"
        echo "input_path = \"$T/templates/kitty-theme.conf\""
        echo "output_path = \"$HOME/.config/kitty/theme.conf\""
        echo "post_hook = \"pkill -USR1 -x kitty || true\""
        echo
        echo "[templates.colors]"
        echo "input_path = \"$T/templates/colors.json\""
        echo "output_path = \"$STATE/colors.json\""
        if $sddm_enabled; then
            echo
            echo "[templates.sddm]"
            echo "input_path = \"$T/templates/sddm.conf.tmpl\""
            echo "output_path = \"/etc/sddm-prasanna/prasanna.conf\""
        fi
    } >"$cfg"
fi
log "matugen config written"

# sudoers: avatar + one exact rule per papirus-folders colour (no wildcards)
tmp="$(mktemp)"
sed -e "s|__USER__|$USER|g" -e "s|__HOME__|$HOME|g" "$DOTFILES/system/sudoers/prasanna-hooks.tmpl" >"$tmp"
for theme in Papirus-Dark Papirus; do
    for c in red carmine deeporange orange yellow green teal cyan darkcyan blue indigo violet magenta pink grey bluegrey; do
        echo "$USER ALL=(root) NOPASSWD: /usr/bin/papirus-folders -C $c --theme $theme" >>"$tmp"
    done
done
if visudo -cqf "$tmp" 2>/dev/null || sudo visudo -cqf "$tmp"; then
    run sudo install -m 440 -o root -g root "$tmp" /etc/sudoers.d/prasanna-hooks
    log "sudoers rules installed (exact commands only)"
else
    err "sudoers template failed validation — not installed"
fi
rm -f "$tmp"

# systemd user units
for u in prasanna-theme.path prasanna-theme.service; do
    symlink "$DOTFILES/system/systemd/$u" "$HOME/.config/systemd/user/$u"
done
run systemctl --user daemon-reload
run systemctl --user enable --now prasanna-theme.path
log "Wallpaper watcher enabled"

# Circular login avatar from ~/.face.icon (only when it exists)
[[ -f "$HOME/.face.icon" ]] && run bash "$DOTFILES/scripts/set-avatar.sh"

info "Running the pipeline once…"
run "$HOME/.local/bin/prasanna-theme" || warn "Pipeline reported a failure — see: prasanna-theme logs (doctor)"
